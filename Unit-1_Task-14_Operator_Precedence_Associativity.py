a = int(input("Enter first number: "))
b = int(input("Enter second number: "))

result1 = a + b * 2
result2 = a - b / 2
result3 = a ** b ** 2
result4 = a + b - 2
result5 = (a + b) * 2

print("A + B * 2 =", result1)
print("A - B / 2 =", result2)
print("A ** B ** 2 =", result3)
print("A + B - 2 =", result4)
print("(A + B) * 2 =", result5)
