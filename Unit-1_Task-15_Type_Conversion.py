a = int(input("Enter an integer: "))
b = float(input("Enter a float value: "))
c = input("Enter a numeric string: ")

# Type conversions
x = float(a)
y = int(b)
z = str(a)
w = int(c)

print("Integer to Float:", x)
print("Float to Integer:", y)
print("Integer to String:", z)
print("String to Integer:", w)

# Display data types
print("Type of x:", type(x))
print("Type of y:", type(y))
print("Type of z:", type(z))
print("Type of w:", type(w))
